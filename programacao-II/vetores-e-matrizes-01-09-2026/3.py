'''3 - Faça um programa que imprima na tela para que servem as seguintes funções do Python:

len(var):

vetor.append(valor): 

vetor.insert(indice, valor):

vetor.extend([array]):

vetor.pop():

vetor.remove(valor):

vetor.sort()

vetor.reverse()'''

print("len(var):")
print("Serve para saber quantos elementos existem dentro de uma variável, como uma lista.")
print("Exemplo: len([10, 20, 30]) retorna 3.\n")

print("vetor.append(valor):")
print("Adiciona um valor no final do vetor.")
print("Exemplo: vetor.append(4) coloca o número 4 na última posição.\n")

print("vetor.insert(indice, valor):")
print("Coloca um valor em uma posição específica do vetor.")
print("Exemplo: vetor.insert(1, 9) coloca o número 9 no índice 1.\n")

print("vetor.extend([array]):")
print("Adiciona vários valores de uma vez no final do vetor.")
print("Exemplo: vetor.extend([5, 6]) coloca os números 5 e 6 no final.\n")

print("vetor.pop():")
print("Remove o último elemento do vetor. Também dá para informar um índice para remover uma posição específica.")
print("Exemplo: vetor.pop() remove o último valor da lista.\n")

print("vetor.remove(valor):")
print("Remove do vetor a primeira ocorrência do valor informado.")
print("Exemplo: vetor.remove(3) remove o primeiro número 3 encontrado.")
print("Obs.: o nome correto é remove, e não removel.\n")

print("vetor.sort():")
print("Organiza os valores do vetor em ordem crescente.")
print("Exemplo: [3, 1, 2].sort() deixaria a lista como [1, 2, 3].\n")

print("vetor.reverse():")
print("Inverte a ordem dos elementos do vetor.")
print("Exemplo: [1, 2, 3].reverse() deixaria a lista como [3, 2, 1].")
